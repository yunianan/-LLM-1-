"""Split human-curated, author-labelled DSM-5 cases without diagnostic leakage.

Input JSONL is deliberately not generated by an LLM. See the adjacent dataset plan.
"""
import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from shared.disorder_catalog import SUPPORTED_DISORDERS

DSM_CATEGORIES = {
    **dict.fromkeys(["D001", "D002", "D003"], "neurodevelopmental"),
    **dict.fromkeys(["D004", "D005", "D006", "D007"], "schizophrenia_spectrum"),
    **dict.fromkeys(["D008", "D009", "D010"], "bipolar"),
    **dict.fromkeys(["D011", "D012"], "anxiety"),
    **dict.fromkeys(["D013", "D014", "D015"], "depressive"),
    **dict.fromkeys(["D016", "D017"], "obsessive_compulsive_related"),
    **dict.fromkeys(["D018", "D019", "D020"], "trauma_stressor_related"),
    **dict.fromkeys(["D021", "D022", "D023"], "feeding_eating"),
    "Insomnia": "sleep_wake",
}


def prepare(records, *, seed=20261014, dev_fraction=38 / 93):
    if not 0 < dev_fraction < 1:
        raise ValueError("dev_fraction must be between 0 and 1")
    strata, excluded, seen_ids, seen_narratives = defaultdict(list), [], set(), set()
    for row in records:
        case_id = row.get("case_id")
        if not isinstance(case_id, str) or not case_id or case_id in seen_ids:
            raise ValueError("Each source case must have a unique case_id; combine multiple QAs first")
        seen_ids.add(case_id)
        reasons = []
        if row.get("source_edition") != "DSM-5": reasons.append("edition_not_DSM5")
        if not row.get("source_ref") or not row.get("author_primary_diagnosis"):
            reasons.append("missing_author_diagnosis_or_source")
        if row.get("mapping_reviewed") is not True: reasons.append("label_mapping_unreviewed")
        if row.get("input_reviewed_no_diagnosis_leak") is not True: reasons.append("input_not_reviewed")
        labels = row.get("gold_labels", [])
        primary = row.get("primary_label")
        if (not isinstance(labels, list) or not labels or
                any(label not in SUPPORTED_DISORDERS for label in labels) or primary not in labels):
            reasons.append("unsupported_or_ambiguous_labels")
        category = row.get("primary_dsm_category")
        if primary in DSM_CATEGORIES and category != DSM_CATEGORIES[primary]:
            reasons.append("incorrect_primary_DSM_category")
        narrative = " ".join(str(row.get("vignette", "")).split())
        if not narrative or not isinstance(row.get("profile"), dict) or not row["profile"]:
            reasons.append("missing_vignette_or_structured_profile")
        if reasons:
            excluded.append({"case_id": case_id, "reasons": reasons})
            continue
        # A duplicate story cannot appear in two partitions under renamed IDs.
        if narrative in seen_narratives:
            raise ValueError("Duplicate vignette: merge at source-case level before splitting")
        seen_narratives.add(narrative)
        strata[category].append(row)
    rng, dev, test, singletons = random.Random(seed), [], [], []
    for category, rows in sorted(strata.items()):
        rows = sorted(rows, key=lambda row: row["case_id"])
        rng.shuffle(rows)
        if len(rows) == 1:
            dev.extend(rows)
            singletons.append(category)
            continue
        n_dev = max(1, min(len(rows) - 1, round(len(rows) * dev_fraction)))
        dev.extend(rows[:n_dev])
        test.extend(rows[n_dev:])
    def counts(rows):
        return dict(Counter(label for row in rows for label in set(row["gold_labels"])))
    test_counts = counts(test)
    report = {"standard": "DSM-5", "seed": seed, "dev_fraction": dev_fraction,
              "included": len(dev) + len(test), "dev": len(dev), "test": len(test),
              "excluded": excluded, "singleton_categories_dev_only": singletons,
              "dev_label_counts": counts(dev), "test_label_counts": test_counts,
              "untested_labels": [label for label in SUPPORTED_DISORDERS if not test_counts.get(label)],
              "strata": {category: len(rows) for category, rows in sorted(strata.items())}}
    return dev, test, report


def write_split(folder, dev, test, report):
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    for partition, rows in [("dev", dev), ("test", test)]:
        # The engine receives ONLY the structured profile. Author labels,
        # diagnosis-bearing titles and expert discussion stay in gold files.
        inputs = [{"case_id": row["case_id"], "profile": row["profile"]} for row in rows]
        gold = [{key: row[key] for key in ("case_id", "source_ref", "source_edition", "author_primary_diagnosis",
                                         "primary_dsm_category", "primary_label", "gold_labels")} for row in rows]
        for suffix, items in [("inputs", inputs), ("gold", gold)]:
            (folder / f"{partition}.{suffix}.jsonl").write_text(
                "".join(json.dumps(item, ensure_ascii=False) + "\n" for item in items), encoding="utf-8")
    (folder / "split_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--seed", type=int, default=20261014)
    parser.add_argument("--dev-fraction", type=float, default=38 / 93)
    args = parser.parse_args()
    records = [json.loads(line) for line in args.input.read_text(encoding="utf-8-sig").splitlines() if line.strip()]
    dev, test, report = prepare(records, seed=args.seed, dev_fraction=args.dev_fraction)
    if not dev or not test:
        raise SystemExit("No usable development/test split. Curate sufficient eligible author-labelled cases first.")
    write_split(args.output, dev, test, report)
    print(f"dev={len(dev)}, test={len(test)}, excluded={len(report['excluded'])}")
